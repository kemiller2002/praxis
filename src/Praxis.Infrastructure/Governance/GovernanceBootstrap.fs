/// The secure bootstrap and the CI verification path (docs/governance/
/// bootstrap.md). Bootstrap writes a *proposal* into the worktree and creates
/// no key: authority exists only once the owner merges it into the protected
/// branch, and once a trust root exists bootstrap refuses to run again, so an
/// ordinary agent cannot repeat or replace it (rotation is an elevated change).
[<RequireQualifiedAccess>]
module GovernanceBootstrap =
    let MergeGateWorkflowPath = ".github/workflows/praxis-merge-gate.yml"
    let RulesetPath = ".praxis/governance/ruleset-main.json"

    /// The protected verification and merge-gate workflow.
    /// The protected verification and merge-gate workflow for `branch`.
    let mergeGateWorkflow (branch: string) =
        $$$"""name: Praxis merge gate

# Generated by `praxis governance bootstrap` (WI-0116). Read from the protected
# branch (pull_request_target, only for pull requests into {{{branch}}}), so a
# candidate cannot change what verifies it. Each mandatory validation runs in
# its own `observe` job, on its own runner, with a read-only token and no OIDC
# permission; candidate code runs there and nowhere else. The gate job never
# executes candidate code: it reads each observe job's conclusion from GitHub's
# own record of this run, binds each result to this workflow's OIDC identity,
# and decides the merge with the Praxis pinned on the protected branch.
# Changing this file is an elevated change.
on:
  pull_request_target:
    branches: [{{{branch}}}]
    types: [opened, synchronize, reopened, ready_for_review]

permissions: {}

concurrency:
  group: praxis-merge-gate-${{ github.event.pull_request.number }}
  cancel-in-progress: true

jobs:
  plan:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read
    outputs:
      validations: ${{ steps.plan.outputs.validations }}
    steps:
      - uses: actions/checkout@v4
        with:
          persist-credentials: false
      - uses: actions/setup-dotnet@v4
        if: hashFiles('Praxis.slnx') != ''
        with:
          dotnet-version: 10.0.x
      - if: hashFiles('Praxis.slnx') != ''
        run: dotnet build Praxis.slnx --configuration Release
      - id: plan
        run: echo "validations=$(./praxis governance validations --policy .praxis/validation-policy.json)" >> "$GITHUB_OUTPUT"

  observe:
    needs: plan
    name: observe (${{ matrix.validation }})
    runs-on: ubuntu-latest
    timeout-minutes: 120
    permissions:
      contents: read
    strategy:
      fail-fast: false
      matrix:
        validation: ${{ fromJSON(needs.plan.outputs.validations) }}
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
          persist-credentials: false
      - name: Fetch the candidate as Git objects
        env:
          PR: ${{ github.event.pull_request.number }}
        run: git fetch --no-tags origin "+refs/pull/$PR/head:refs/praxis/candidate"
      - uses: actions/setup-dotnet@v4
        if: hashFiles('Praxis.slnx') != ''
        with:
          dotnet-version: 10.0.x
      - if: hashFiles('Praxis.slnx') != ''
        run: dotnet build Praxis.slnx --configuration Release
      - name: Run one protected validation on the candidate
        env:
          HEAD_SHA: ${{ github.event.pull_request.head.sha }}
          VALIDATION: ${{ matrix.validation }}
        run: ./praxis governance observe --candidate "$HEAD_SHA" --validation "$VALIDATION" --policy .praxis/validation-policy.json

  praxis-merge-gate:
    needs: [plan, observe]
    if: always()
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read
      actions: read
      pull-requests: read
      id-token: write
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
          persist-credentials: false
      - name: Fetch the candidate as Git objects
        env:
          PR: ${{ github.event.pull_request.number }}
        run: git fetch --no-tags origin "+refs/pull/$PR/head:refs/praxis/candidate"
      - uses: actions/setup-dotnet@v4
        if: hashFiles('Praxis.slnx') != ''
        with:
          dotnet-version: 10.0.x
      - if: hashFiles('Praxis.slnx') != ''
        run: dotnet build Praxis.slnx --configuration Release
      - name: Attest this run's observe conclusions with the workflow's identity
        env:
          PR: ${{ github.event.pull_request.number }}
          HEAD_SHA: ${{ github.event.pull_request.head.sha }}
          GITHUB_TOKEN: ${{ github.token }}
        run: |
          ./praxis governance attest --repository "$GITHUB_REPOSITORY" --run-id "$GITHUB_RUN_ID" --pull-request "$PR" \
            --candidate "$HEAD_SHA" --policy .praxis/validation-policy.json --out "$RUNNER_TEMP/receipts" \
            || echo "::warning::attestation failed; the decision below will refuse"
      - name: Decide the merge
        env:
          PR: ${{ github.event.pull_request.number }}
          HEAD_SHA: ${{ github.event.pull_request.head.sha }}
          GITHUB_TOKEN: ${{ github.token }}
        run: |
          ./praxis merge authorize --repository "$GITHUB_REPOSITORY" --base "origin/{{{branch}}}" \
            --candidate "$HEAD_SHA" --pull-request "$PR" --receipts "$RUNNER_TEMP/receipts" \
            --live --evidence-out "$RUNNER_TEMP/decision/merge-decision.json"
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: praxis-merge-decision
          path: |
            ${{ runner.temp }}/decision
            ${{ runner.temp }}/receipts
          retention-days: 90
"""

    /// The default-branch ruleset the owner imports (Settings > Rules >
    /// Rulesets > Import). No bypass actors: rules apply to administrators.
    let ruleset (branch: string) =
        $$"""{
  "name": "praxis-protected-{{branch}}",
  "target": "branch",
  "enforcement": "active",
  "bypass_actors": [],
  "conditions": { "ref_name": { "include": ["refs/heads/{{branch}}"], "exclude": [] } },
  "rules": [
    { "type": "deletion" },
    { "type": "non_fast_forward" },
    { "type": "pull_request", "parameters": {
        "required_approving_review_count": 0,
        "dismiss_stale_reviews_on_push": true,
        "require_code_owner_review": false,
        "require_last_push_approval": false,
        "required_review_thread_resolution": false } },
    { "type": "required_status_checks", "parameters": {
        "strict_required_status_checks_policy": true,
        "required_status_checks": [ { "context": "praxis-merge-gate", "integration_id": 15368 } ] } }
  ]
}
"""

    let private write (root: string) (relative: string) (text: string) =
        let path = Path.Combine(root, relative)
        Directory.CreateDirectory(Path.GetDirectoryName path) |> ignore
        File.WriteAllText(path, text, UTF8Encoding(false))
        relative

    let private arr (values: string list) = JsonArray(values |> List.map (fun v -> JsonValue.Create v :> JsonNode) |> List.toArray)

    /// Write the bootstrap proposal. Refuses when the protected branch (or the
    /// worktree) already has a trust root: replacing one is a rotation.
    let bootstrap (request: BootstrapRequest) : Result<string list, string> =
        let protectedTrust =
            GovernanceGit.resolve request.Root request.BaseRef
            |> Result.bind (fun head -> GovernanceGit.show request.Root head GovernanceOperations.TrustRootPath)

        match protectedTrust with
        | Error reason -> Error $"the protected branch '{request.BaseRef}' cannot be read ({reason}); bootstrap refuses rather than assume no trust root exists"
        | Ok(Some _) -> Error "the protected branch already has a completion authority trust root; bootstrap runs once. Rotate or revoke through an elevated change (docs/governance/bootstrap.md)."
        | _ when File.Exists(Path.Combine(request.Root, GovernanceOperations.TrustRootPath)) ->
            Error "the worktree already has a proposed trust root; review or remove it before bootstrapping again"
        | _ when request.Validations.IsEmpty -> Error "name at least one mandatory validation (--validation NAME=COMMAND)"
        | _ when not (request.Repository.Contains '/') -> Error "--repository must be OWNER/NAME"
        | _ ->
            try
                let trust: VerifierTrustRoot =
                    { ConfigVersion = 1
                      Repository = request.Repository
                      ApprovedBy = request.ApprovedBy
                      ApprovedAt = request.Now
                      Verifiers =
                        [ { Id = "merge-gate-v1"
                            Identity =
                              VerifierIdentity.Workload
                                  { Issuer = VerifierTrust.GitHubIssuer
                                    Repository = request.Repository
                                    WorkflowRef = $"{request.Repository}/{MergeGateWorkflowPath}@refs/heads/{request.Branch}"
                                    Events = [ "pull_request_target" ] }
                            ValidFrom = request.Now
                            ValidUntil = None
                            RevokedAt = None
                            RevocationReason = None
                            PolicyScopes = [] } ] }

                let policy = JsonObject()
                policy["schemaVersion"] <- JsonValue.Create "echelon.validation-policy/1"
                policy["policyId"] <- JsonValue.Create(request.Repository.Replace('/', '-') + "-merge-gate-v1")
                policy["repository"] <- JsonValue.Create request.Repository
                let validations = JsonArray()

                for name, command in request.Validations do
                    let v = JsonObject()
                    v["name"] <- JsonValue.Create name
                    v["evidenceId"] <- JsonValue.Create name
                    v["command"] <- arr command
                    v["timeoutSeconds"] <- JsonValue.Create 1800
                    validations.Add v

                policy["validations"] <- validations
                policy["protectedPaths"] <- JsonArray()

                let authorities = JsonObject()
                authorities["schema"] <- JsonValue.Create "praxis.governance-authorities/1"
                authorities["workAuthorizers"] <- arr [ request.ApprovedBy ]
                authorities["elevatedApprovers"] <- arr [ request.ApprovedBy ]
                authorities["exceptionAuthorities"] <- arr [ request.ApprovedBy ]
                authorities["agentIdentities"] <- arr request.AgentIdentities

                let rosPath = Path.Combine(request.Root, "ros.json")

                let rosUpdated =
                    if File.Exists rosPath then
                        let ros = JsonNode.Parse(File.ReadAllText rosPath).AsObject()
                        let governance = match ros["governance"] with :? JsonObject as g -> g | _ -> JsonObject()
                        governance["requireVerifiedMerge"] <- JsonValue.Create true
                        let check = JsonObject()
                        check["context"] <- JsonValue.Create "praxis-merge-gate"
                        check["integrationId"] <- JsonValue.Create PlatformGovernance.GitHubActionsIntegrationId
                        governance["requiredChecks"] <- JsonArray(check)
                        ros["governance"] <- governance
                        [ write request.Root "ros.json" (GovernanceJson.indented ros + "\n") ]
                    else []

                Ok(
                    [ write request.Root GovernanceOperations.TrustRootPath (GovernanceJson.indented (GovernanceJson.renderTrustRoot trust) + "\n")
                      write request.Root GovernanceOperations.PolicyPath (GovernanceJson.indented policy + "\n")
                      write request.Root GovernanceOperations.AuthoritiesPath (GovernanceJson.indented authorities + "\n")
                      write request.Root MergeGateWorkflowPath (mergeGateWorkflow request.Branch)
                      write request.Root RulesetPath (ruleset request.Branch) ]
                    @ rosUpdated
                )
            with error ->
                Error error.Message

    // ---- CI: observe and attest -----------------------------------------------

    /// The policy's validation names as a JSON array (the CI matrix).
    let validations (policyFile: string) =
        ValidationPolicyJson.readFile policyFile
        |> Result.map (fun policy -> GovernanceJson.compact (JsonArray(policy.Validations |> List.map (fun v -> JsonValue.Create v.Name :> JsonNode) |> List.toArray)))

    /// Run one protected validation on the candidate (a CI `observe` job).
    /// Its only output that matters is the exit code GitHub records as the
    /// job's conclusion; the ephemeral receipt is discarded.
    let observe (request: ObserveRequest) : Result<bool * string, string> =
        ValidationPolicyJson.readFile request.PolicyFile
        |> Result.bind (fun policy ->
            match policy.Validations |> List.filter (fun v -> v.Name = request.Validation) with
            | [] -> Error $"the protected policy has no validation '{request.Validation}'"
            | selected ->
                let verify: VerifyRequest =
                    { RepoPath = request.Root
                      WorkItemId = "observation"
                      Claimant = "ci"
                      FencingGeneration = 0L
                      Commit = request.Candidate
                      Remote = None }

                match TrustedVerifierEngine.observe (VerifierKey.generate ()) { policy with Validations = selected } policy.Digest verify with
                | VerifierResponse.Refused(code, detail) -> Error $"{code}: {detail}"
                | VerifierResponse.Signed(receipts, diagnostics) ->
                    let output = (receipts |> List.map _.Output |> String.concat "\n") + (diagnostics |> String.concat "\n")
                    Ok(receipts |> List.forall (fun r -> r.Payload.Status = CheckStatus.Passed), output))

    /// A GitHub Actions OIDC token for `audience` (job needs id-token: write).
    let private requestToken (audience: string) =
        match Environment.GetEnvironmentVariable "ACTIONS_ID_TOKEN_REQUEST_URL", Environment.GetEnvironmentVariable "ACTIONS_ID_TOKEN_REQUEST_TOKEN" with
        | (null | ""), _
        | _, (null | "") -> Error "no OIDC token endpoint: run inside GitHub Actions with permission id-token: write"
        | url, bearer ->
            try
                use client = new HttpClient(Timeout = TimeSpan.FromSeconds 30.0)
                use message = new HttpRequestMessage(HttpMethod.Get, $"{url}&audience={Uri.EscapeDataString audience}")
                message.Headers.Authorization <- Headers.AuthenticationHeaderValue("Bearer", bearer)
                use response = client.Send message
                use reader = new StreamReader(response.Content.ReadAsStream())
                let body = reader.ReadToEnd()

                if response.IsSuccessStatusCode then Ok((JsonNode.Parse body).["value"].ToString())
                else Error $"the OIDC endpoint answered HTTP {int response.StatusCode}"
            with error ->
                Error error.Message

    /// The receipt status a job conclusion attests. Anything but success is
    /// not a pass; a job that did not finish is unavailable.
    let statusOf (conclusion: string) =
        match conclusion with
        | "success" -> CheckStatus.Passed, Some 0
        | "failure" -> CheckStatus.Failed, Some 1
        | _ -> CheckStatus.Unavailable, None

    /// Build one receipt per protected validation from this run's `observe`
    /// job conclusions, as GitHub recorded them, and bind each to this
    /// workflow's OIDC identity. Nothing written by candidate code is read.
    let attest (request: AttestRequest) : Result<string list, string> =
        ValidationPolicyJson.readFile request.PolicyFile
        |> Result.bind (fun policy ->
            GitHubGovernance.getPull request.Repository request.PullRequest
            |> Result.bind (fun pull ->
                match GovernanceOperations.declaredIn pull.Body with
                | [] -> Error $"pull request #{request.PullRequest} declares no 'Praxis-Work-Item: ID'"
                | workItem :: _ ->
                    if pull.HeadSha <> request.Candidate then Error "the pull request's head moved; the gate re-runs for the new head"
                    else
                        GovernanceGit.tree request.Root request.Candidate
                        |> Result.bind (fun treeId ->
                            GitHubGovernance.runJobs request.Repository request.RunId
                            |> Result.bind (fun jobs ->
                                try
                                    Directory.CreateDirectory request.OutDirectory |> ignore

                                    policy.Validations
                                    |> List.map (fun validation ->
                                        let conclusion, started, completed, jobId =
                                            jobs
                                            |> List.tryFind (fun (name, _) -> name = $"observe ({validation.Name})")
                                            |> Option.map snd
                                            |> Option.defaultValue ("missing", None, None, "none")

                                        let status, exitCode = statusOf conclusion
                                        let observedAt = completed |> Option.defaultValue (DateTimeOffset.UtcNow)
                                        let startedAt = started |> Option.defaultValue observedAt

                                        let payload: ReceiptPayload =
                                            { ReceiptId = Guid.NewGuid().ToString()
                                              WorkItemId = workItem
                                              Claimant = $"pull-request/{request.PullRequest}"
                                              FencingGeneration = 0L
                                              Commit = request.Candidate
                                              TreeId = treeId
                                              OrdoContractDigest = policy.Digest
                                              ValidationPolicyId = policy.PolicyId
                                              ValidationPolicyDigest = policy.Digest
                                              Validation = validation.Name
                                              EvidenceId = validation.EvidenceId
                                              Status = status
                                              ExitCode = exitCode
                                              Command = validation.Command
                                              OutputSha256 = CompletionGate.sha256 (Encoding.UTF8.GetBytes $"{request.Repository}/actions/runs/{request.RunId}/job/{jobId}:{conclusion}")
                                              StartedAt = startedAt
                                              ObservedAt = observedAt
                                              DurationMs = int64 (observedAt - startedAt).TotalMilliseconds
                                              Verifier = { Id = "praxis-merge-gate"; Version = TrustedVerifierEngine.version; KeyId = $"workload:run/{request.RunId}" } }

                                        let bytes = VerificationReceipt.render payload

                                        requestToken (VerifierTrust.audienceFor bytes)
                                        |> Result.map (fun token ->
                                            let out = Path.Combine(request.OutDirectory, $"{validation.Name}.workload.json")
                                            let receipt: VerifierTrust.WorkloadReceipt = { Payload = bytes; Token = token }
                                            File.WriteAllText(out, GovernanceJson.indented (GovernanceJson.renderWorkloadReceipt receipt), UTF8Encoding(false))
                                            out))
                                    |> List.fold (fun acc r -> match acc, r with Ok xs, Ok x -> Ok(xs @ [ x ]) | Error e, _ -> Error e | _, Error e -> Error e) (Ok [])
                                with error ->
                                    Error error.Message))))

/// File and clock effects the CLI adapter delegates (the CLI owns none).
[<RequireQualifiedAccess>]
module GovernanceFiles =
    let now () = DateTimeOffset.UtcNow

    let readJson (path: string) =
        try
            Ok(JsonNode.Parse(File.ReadAllText path))
        with error ->
            Error $"cannot read '{path}': {error.Message}"

    let writeText (path: string) (text: string) =
        try
            match Path.GetDirectoryName(Path.GetFullPath path) with
            | null -> ()
            | directory -> Directory.CreateDirectory directory |> ignore

            File.WriteAllText(path, text, UTF8Encoding(false))
            Ok()
        with error ->
            Error $"cannot write '{path}': {error.Message}"

    /// A `--validation NAME=COMMAND` value: the command is a JSON array of
    /// arguments (`tests=["sh","-c","make test"]`) or space-separated words.
    let validationArgument (text: string) =
        match text.Split('=', 2) with
        | [| name; command |] when name <> "" && command.Trim().StartsWith "[" ->
            try
                let parts = (JsonNode.Parse command).AsArray() |> Seq.map (fun p -> p.GetValue<string>()) |> Seq.toList
                if parts.IsEmpty then Error $"--validation '{name}' has an empty command" else Ok(name, parts)
            with error ->
                Error $"--validation '{name}': {error.Message}"
        | [| name; command |] when name <> "" && command.Trim() <> "" -> Ok(name, command.Split(' ', StringSplitOptions.RemoveEmptyEntries) |> Array.toList)
        | _ -> Error $"--validation '{text}' must be NAME=COMMAND or NAME=[\"arg\",...]"

/// Compact human-readable summaries; `--json` prints the full documents.
[<RequireQualifiedAccess>]
module GovernanceText =
    let report (r: GovernanceReport) =
        [ $"governance: {r.Repository} ({r.Branch}) readiness {ReadinessLevel.toWire r.Level}"
          for c in r.Controls do
              let mark = if ControlStatus.isSatisfied c.Status then "ok " else "-- "
              $"  {mark}{c.Id} [{ControlStatus.toWire c.Status}] {c.Detail}"
              if not (ControlStatus.isSatisfied c.Status) && c.Remedy <> "" then $"      remedy ({Principal.toWire c.ResolvedBy}): {c.Remedy}"
          for b in r.ResidualTrustBoundaries do
              $"  residual: {b}" ]
        |> String.concat "\n"

    let decision (d: MergeDecision) =
        [ $"merge {MergeOutcome.toWire d.Outcome}: {d.CandidateHead} -> {d.TargetBranch} ({d.TargetHead})"
          for b in d.AuthorizationBasis do
              $"  authorized: {b}"
          for r in d.Receipts do
              $"  receipt: {r.Payload.Validation} {CheckStatus.code r.Payload.Status} at {r.Payload.Commit} by {r.VerifierId} ({AuthenticationBasis.toWire r.Basis})"
          for f in d.Refusals do
              $"  REFUSED {f.Code}: {f.Detail}\n      remedy ({Principal.toWire f.ResolvedBy}): {f.Remedy}"
          for f in d.Waived do
              $"  waived {f.Code}: {f.Detail}"
          for a in d.Advisories do
              $"  advisory: {a}" ]
        |> String.concat "\n"

    let audit (r: IntegrationAuditReport) =
        [ $"audit: {r.Branch} at {r.Head}: {r.Examined} integration(s), {r.VerifiedIntegrations} verified, {r.Findings.Length} finding(s)"
          for f in r.Findings do
              $"  {f.Severity} {f.Code} {f.Commit.Substring(0, min 12 f.Commit.Length)}: {f.Detail}" ]
        |> String.concat "\n"

    let diagnosis (d: CompletionAuthorityDiagnosis) =
        let next = String.concat "; " d.Procedure

        if d.Ready then $"completion authority: ready ({d.Path})\n  next: {next}"
        else
            [ "completion authority: NOT PROVISIONED"
              for m in d.Missing do
                  $"  missing: {m}"
              $"  why: {d.Why}"
              for r in d.Reusable do
                  $"  reuse: {r}"
              $"  resolved by: {Principal.toWire d.ResolvedBy}"
              for p in d.Procedure do
                  $"  step: {p}"
              for c in d.MayContinue do
                  $"  may continue: {c}"
              for b in d.Blocked do
                  $"  blocked: {b}" ]
            |> String.concat "\n"
