def excluded_reduction(ix: Index, study: str, unit: str, metric: str, session_metric: str,
                       excluded: tuple[str, ...]) -> float:
    def value(arm: str, u: str, met: str) -> float:
        r = ix.rows.get((study, arm, u, met))
        if r is None or r["value"] is None or r["completeness"] != "complete":
            raise KeyError(f"excluded-sessions macro: no complete row {(study, arm, u, met)}")
        return r["value"]
    grouped = value(G, unit, metric)
    independent = value(I, unit, metric) - sum(value(I, u, session_metric) for u in excluded)
    return (independent - grouped) / independent


def macro_value(ix: Index, m: Macro) -> str:
    if m.kind == "excluded":
        return FMT[m.fmt](excluded_reduction(ix, *m.key))
    if m.kind == "row":
        r = ix.rows.get(m.key)
        if r is None:
            raise KeyError(f"macro {m.name}: no row {m.key}")
        return cell(r, m.fmt).replace("$\\geq$", "\\ensuremath{\\geq}")
    d = ix.derived.get(m.key[:3])
    if d is None:
        raise KeyError(f"macro {m.name}: no derived {m.key}")
    return "n/a" if d[m.key[3]] is None else FMT[m.fmt](d[m.key[3]])


def macros_tex(ix: Index) -> str:
    names = [m.name for m in MACROS]
    dupes = sorted({n for n in names if names.count(n) > 1})
    bad = sorted(n for n in names if not n.isalpha())
    if dupes or bad:
        raise ValueError(f"macro names: duplicates {dupes}, non-letters {bad}")
    lines = (f"\\newcommand{{\\{m.name}}}{{{macro_value(ix, m)}}} % {tex_escape(m.comment)}" for m in MACROS)
    return (HEADER + "% Numbers only (no units or % signs). Lower bounds carry \\ensuremath{\\geq}.\n"
            "% Reductions are percentages; ratios are independent/grouped.\n" + "\n".join(lines) + "\n")


def render(doc: Mapping[str, Any]) -> Mapping[str, str]:
    ix = index(doc)
    return MappingProxyType({
        "resources-a021.tex": resource_table(ix, "A021", A021_LINES,
                                             "A021 resources and repeated work, grouped versus independent execution",
                                             "tab:resources-a021", A021_NOTES),
        "resources-r2.tex": resource_table(ix, "R2", R2_LINES,
                                           "R2 resources and repeated work, grouped versus independent execution",
                                           "tab:resources-r2", R2_NOTES),
        "quality-counts.tex": quality_table(ix),
        "macros.tex": macros_tex(ix),
    })


def main(argv: Sequence[str]) -> int:
    files = render(json.loads(DATA.read_text(encoding="utf-8")))
    if "--check" in argv:
        stale = tuple(n for n, t in sorted(files.items())
                      if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t)
        tuple(print(f"STALE manuscript/tables/{n}") for n in stale)
        print("tables up to date" if not stale else f"{len(stale)} table file(s) differ")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    tuple((OUT / n).write_text(t, encoding="utf-8") for n, t in sorted(files.items()))
    print("\n".join(f"manuscript/tables/{n}" for n in sorted(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
