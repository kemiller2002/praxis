# --------------------------------------------------------------------------
# Formatting (pure)
# --------------------------------------------------------------------------

Fmt = Callable[[Any], str]

FMT: Mapping[str, Fmt] = MappingProxyType({
    "int": lambda v: f"{int(v):,}",
    "usd": lambda v: f"{v:.2f}",
    "usd7": lambda v: f"{v:.7f}",
    "mtok": lambda v: f"{v / 1e6:.2f}",
    "ktok": lambda v: f"{v / 1e3:.1f}",
    "min": lambda v: f"{v / 60:.1f}",
    "hmin": lambda v: f"{int(v) // 3600}:{round((int(v) % 3600) / 60):02d}",
    "hms": lambda v: (lambda s: f"{s // 3600}h{(s % 3600) // 60:02d}m{s % 60:02d}s")(int(round(v))),
    "ratio": lambda v: f"{v:.2f}",
    "ratio4": lambda v: f"{v:.4f}",
    "pct1": lambda v: f"{v * 100:.1f}",
    "pct2": lambda v: f"{v * 100:.2f}",
})


def cell(r: Optional[Mapping[str, Any]], fmt: str) -> str:
    if r is None:
        return "--"
    if r["value"] is None:
        return "--" if r["completeness"] == "not_applicable" else "n/a"
    text = FMT[fmt](r["value"])
    return ("$\\geq$" + text) if r["completeness"] == "lower_bound" else text


def dcell(d: Optional[Mapping[str, Any]], field: str, fmt: str) -> str:
    if d is None or d[field] is None:
        return "n/a"
    text = FMT[fmt](d[field])
    return text + ("$^{\\ast}$" if d["completeness"] != "complete" else "")


def tex_escape(s: str) -> str:
    return s.replace("%", "\\%").replace("&", "\\&").replace("_", "\\_").replace("#", "\\#")


