"""Generate LaTeX metric tables and prose macros from data/metrics.json.

Outputs (manuscript/tables/):
  resources-a021.tex  A021 resource and work metrics, grouped vs independent
  resources-r2.tex    R2 resource and work metrics, both orchestration definitions
  quality-counts.tex  test and defect counts per evaluation (counts only)
  macros.tex          \\newcommand for every number used in prose

Every number comes from metrics.json; nothing is typed by hand. Plain
``tabular`` with \\hline (compatible with IEEEtran; no booktabs needed).
Markers: ``$\\geq$`` lower bound; ``n/a`` unknown; ``--`` not applicable;
``$^{\\ast}$`` ratio/reduction computed from partial or lower-bound operands.
No p-values, confidence intervals or cross-study means are produced.

Usage: python3 scripts/build_tables.py [--check]
"""
